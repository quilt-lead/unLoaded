"""Write the double-click build: viewers/drawings.html, viewers/calcs.html, viewers/index.html.

Browsers won't load module files, JSON or PDFs by fetch from a page opened from disk (file://), so each page
gets its code and styles inline, and the data and PDFs are shipped as plain scripts in viewers/assets/:
  assets/data.js        window.CALC_DATA = {...the data/*.json files...}
  assets/pdf-<doc>.js   window.PDF_DATA[<doc>] = "<base64 PDF>"   (git-ignored: copyrighted source documents)

Run after build.py (build.py calls it):  python prototyping/calc-viewer/build/make_viewers.py
"""
from __future__ import annotations

import base64
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
VIEWER = HERE.parent
REPO = VIEWER.parent.parent
SRC = VIEWER / "viewer"
DATA = VIEWER / "data"
OUT = VIEWER / "viewers"
ASSETS = OUT / "assets"

# modules in dependency order; their local imports/exports are stripped and the code concatenated
BUNDLES = {
    "drawings.html": ["data.js", "stepper.js", "pdfpane.js", "pagenav.js", "windows.js", "app.js"],
    "calcs.html": ["data.js", "stepper.js", "pdfpane.js", "pagenav.js", "windows.js", "app.js"],
    "index.html": ["data.js", "windows.js", "index.js"],
}
PDFS_FOR = {"drawings.html": ["plans"], "calcs.html": ["calcs", "stair"], "index.html": []}

LOCAL_IMPORT = re.compile(r'^\s*import\s+[^;]*?\s+from\s+"\./[^"]+";\s*$', re.M)
EXPORT = re.compile(r"^export\s+(?=(async\s+)?function|const|let|class)", re.M)


def bundle(files: list[str]) -> str:
    parts = []
    for f in files:
        code = (SRC / f).read_text(encoding="utf-8")
        code = LOCAL_IMPORT.sub("", code)
        code = EXPORT.sub("", code)
        parts.append(f"// ---- {f}\n{code}")
    js = "\n".join(parts)
    if "</script" in js.lower():
        raise ValueError("bundle contains '</script' and cannot be inlined")
    return js


def write_assets():
    ASSETS.mkdir(parents=True, exist_ok=True)
    data = {n: json.loads((DATA / f"{n}.json").read_text(encoding="utf-8"))
            for n in ("documents", "elements", "groups", "calcs", "links")}
    (ASSETS / "data.js").write_text("window.CALC_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                                    encoding="utf-8")
    sources = {"plans": VIEWER / "docs" / "plans-S.pdf",
               "calcs": REPO / "pdfs" / "OC-DPH_PKG21-0516_Bldg12_Calcs.pdf",
               "stair": REPO / "pdfs" / "OC-DPH_PKG21-0516_Bldg12_StairCalcs.pdf"}
    for doc, path in sources.items():
        out = ASSETS / f"pdf-{doc}.js"
        if out.exists() and out.stat().st_mtime >= path.stat().st_mtime:
            continue
        b64 = base64.b64encode(path.read_bytes()).decode("ascii")
        out.write_text(f'(window.PDF_DATA = window.PDF_DATA || {{}})["{doc}"] = "{b64}";\n', encoding="ascii")


def write_pages():
    css = (SRC / "style.css").read_text(encoding="utf-8")
    for page, files in BUNDLES.items():
        html = (VIEWER / page).read_text(encoding="utf-8")
        html = html.replace('<link rel="stylesheet" href="viewer/style.css">', f"<style>\n{css}\n</style>")
        scripts = ['<script src="assets/data.js"></script>'] + [f'<script src="assets/pdf-{d}.js"></script>' for d in PDFS_FOR[page]]
        mod = f'<script type="module">\n{bundle(files)}\n</script>'
        src_tag = re.search(r'<script type="module" src="viewer/[a-z]+\.js"></script>', html).group(0)
        html = html.replace(src_tag, "\n".join(scripts) + "\n" + mod)
        html = html.replace("<head>", "<head>\n<!-- Generated by build/make_viewers.py – edit viewer/*.js and the pages in calc-viewer/, then rebuild. -->", 1)
        (OUT / page).write_text(html, encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    write_assets()
    write_pages()
    sizes = {p.name: f"{p.stat().st_size / 1e6:.1f} MB" for p in sorted(OUT.rglob("*")) if p.is_file()}
    print("viewers:", sizes)


if __name__ == "__main__":
    main()
