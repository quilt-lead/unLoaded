"""Generate frontend/src/types/schema.ts from the Pydantic schema (backend/calcgraph/schema).

    uv run python scripts/gen_ts_types.py           # write the file
    uv run python scripts/gen_ts_types.py --check   # exit 1 if the file is stale

Pydantic -> JSON Schema (validation mode) -> json-schema-to-typescript, pinned below and run
through npx (not a frontend dependency, so it never enters the app bundle). The generated
file is not imported by the frontend yet.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from calcgraph.schema.models import SCHEMA_VERSION, TS_MODELS  # noqa: E402

GENERATOR = "json-schema-to-typescript@15.0.4"  # pinned exact version (published 2025-01-14)
OUT = os.path.join(ROOT, "frontend", "src", "types", "schema.ts")


def _draft07(node, keep_title: bool = False):
    """Pydantic emits draft 2020-12; json-schema-to-typescript reads draft-07. Drop per-property
    titles (they become one alias type per field) and turn prefixItems into tuple items."""
    if isinstance(node, list):
        return [_draft07(x) for x in node]
    if not isinstance(node, dict):
        return node
    out = {}
    for k, v in node.items():
        if k == "title" and not keep_title:
            continue
        if k == "prefixItems":
            out["items"] = _draft07(v)
            out["minItems"] = out["maxItems"] = len(v)
            continue
        if k == "properties":
            out[k] = {name: _draft07(sub) for name, sub in v.items()}
            continue
        out[k] = _draft07(v)
    return out


def json_schema() -> dict:
    _, top = models_json_schema([(m, "validation") for m in TS_MODELS], ref_template="#/$defs/{model}")
    defs = {name: _draft07(d, keep_title=True) for name, d in top["$defs"].items()}
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "CalcGraphSchema",
        "description": f"{SCHEMA_VERSION} - generated from backend/calcgraph/schema, do not edit",
        "type": "object",
        "properties": {m.__name__: {"$ref": f"#/$defs/{m.__name__}"} for m in TS_MODELS},
        "additionalProperties": False,
        "$defs": defs,
    }


def generate() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "schema.json")
        dst = os.path.join(tmp, "schema.ts")
        with open(src, "w") as fh:
            json.dump(json_schema(), fh, indent=1, sort_keys=True)
        banner = (f"/* Generated by scripts/gen_ts_types.py ({GENERATOR}) from {SCHEMA_VERSION}.\n"
                  f" * Do not edit: change backend/calcgraph/schema and re-run the script. */")
        subprocess.run(["npx", "--yes", f"--package={GENERATOR}", "json2ts", "--input", src, "--output", dst,
                        "--bannerComment", banner, "--unreachableDefinitions", "--additionalProperties", "false",
                        "--format", "false"], check=True, cwd=tmp)
        return open(dst).read()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    ts = generate()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != ts:
            print(f"{os.path.relpath(OUT, ROOT)} is stale - run scripts/gen_ts_types.py")
            return 1
        print("schema.ts up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(ts)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(ts.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
